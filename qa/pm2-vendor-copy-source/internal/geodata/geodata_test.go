var fixtureNow = time.Date(2026, 10, 13, 12, 0, 0, 0, time.UTC)

// A small synthetic MMDB, explicitly not provider or visitor evidence. One
// root node maps both branches to the same record, allowing schema/corruption
// tests without downloading a 121 MiB database in every unit test.
func mmdbHeader(kind byte, size int) []byte {
	if size >= 29 {
		panic("fixture too large")
	}
	if kind >= 8 {
		return []byte{byte(size), kind - 7}
	}
	return []byte{kind<<5 | byte(size)}
}
func mmdbValue(v any) []byte {
	var out []byte
	switch value := v.(type) {
	case string:
		out = mmdbHeader(2, len(value))
		out = append(out, []byte(value)...)
	case uint32:
		out = mmdbHeader(6, 4)
		out = binary.BigEndian.AppendUint32(out, value)
	case uint64:
		out = mmdbHeader(9, 8)
		out = binary.BigEndian.AppendUint64(out, value)
	case float64:
		out = mmdbHeader(3, 8)
		out = binary.BigEndian.AppendUint64(out, math.Float64bits(value))
	case map[string]any:
		out = mmdbHeader(7, len(value))
		// Map ordering is immaterial to the database. Each test signs the actual
		// generated bytes; no fixture digest stands in for provider verification.
		for k, v := range value {
			out = append(out, mmdbValue(k)...)
			out = append(out, mmdbValue(v)...)
		}
	case []any:
		out = mmdbHeader(11, len(value))
		for _, v := range value {
			out = append(out, mmdbValue(v)...)
		}
	default:
		panic("unsupported fixture value")
	}
	return out
}
func fixtureRecord() map[string]any {
	return map[string]any{
		"country":      map[string]any{"iso_code": "US", "names": map[string]any{"en": "United States", "zh-CN": "美国"}},
		"city":         map[string]any{"names": map[string]any{"en": "Test City", "zh-CN": "测试城市"}},
		"subdivisions": []any{map[string]any{"names": map[string]any{"en": "Test Region"}}},
		"location":     map[string]any{"latitude": float64(12.3), "longitude": float64(45.6)},
	}
}
func fixtureDatabase(record map[string]any) []byte {
	out := []byte{0, 0, 17, 0, 0, 17}
	out = append(out, make([]byte, 16)...)
	out = append(out, mmdbValue(record)...)
	out = append(out, []byte("\xAB\xCD\xEFMaxMind.com")...)
	metadata := map[string]any{"node_count": uint32(1), "record_size": uint32(24), "ip_version": uint32(6), "database_type": "DBIP-City-Lite", "binary_format_major_version": uint32(2), "binary_format_minor_version": uint32(0), "build_epoch": uint64(time.Date(2026, 10, 1, 0, 0, 0, 0, time.UTC).Unix()), "languages": []any{"en", "zh-CN"}, "description": map[string]any{"en": "Synthetic unit-test city"}}
	return append(out, mmdbValue(metadata)...)
}
func gzipFixture(t *testing.T, raw []byte) []byte {
	t.Helper()
	var b bytes.Buffer
	w := gzip.NewWriter(&b)
	if _, err := w.Write(raw); err != nil {
		t.Fatal(err)
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}
func manifestFor(raw, compressed []byte) Manifest {
	return Manifest{Format: 1, Channel: Channel, Release: "2026-10", BuildEpoch: uint64(time.Date(2026, 10, 1, 0, 0, 0, 0, time.UTC).Unix()), CompressedBytes: int64(len(compressed)), CompressedSHA256: hash(compressed), Bytes: int64(len(raw)), SHA256: hash(raw), Source: "https://download.db-ip.com/free/dbip-city-lite-2026-10.mmdb.gz", License: LicenseURL, AttributionURL: AttributionURL}
}
func testAuthority(t *testing.T, m Manifest) (Authority, ed25519.PublicKey, ed25519.PrivateKey, []byte, []byte) {
	t.Helper()
	pub, private, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	raw, err := json.Marshal(m)
	if err != nil {
		t.Fatal(err)
	}
	sig := []byte(base64.StdEncoding.EncodeToString(ed25519.Sign(private, append([]byte(SignatureDomain), raw...))))
	a, err := VerifyManifest(raw, sig, pub, fixtureNow, nil)
	if err != nil {
		t.Fatal(err)
	}
	return a, pub, private, raw, sig
}
func openFixture(t *testing.T, row map[string]any) *Snapshot {
	t.Helper()
	data := fixtureDatabase(row)
	compressed := gzipFixture(t, data)
	a, _, _, _, _ := testAuthority(t, manifestFor(data, compressed))
	s, err := Open(context.Background(), a, bytes.NewReader(compressed))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { s.Close() })
	return s
}

func TestManifestClosedSigningAndRollback(t *testing.T) {
	data := fixtureDatabase(fixtureRecord())
	compressed := gzipFixture(t, data)
	a, pub, key, raw, sig := testAuthority(t, manifestFor(data, compressed))
	if _, err := VerifyManifest(raw, sig, pub, fixtureNow, &a); err != nil {
		t.Fatal(err)
	}
	for name, change := range map[string]func([]byte) []byte{
		"duplicate":    func(b []byte) []byte { return append([]byte(`{"format":1,`), b[1:]...) },
		"alias":        func(b []byte) []byte { return bytes.Replace(b, []byte(`"format"`), []byte(`"Format"`), 1) },
		"unknown":      func(b []byte) []byte { return append([]byte(`{"command":"curl|sh",`), b[1:]...) },
		"null":         func(b []byte) []byte { return bytes.Replace(b, []byte(`"format":1`), []byte(`"format":null`), 1) },
		"missing":      func(b []byte) []byte { return bytes.Replace(b, []byte(`"format":1,`), nil, 1) },
		"extra":        func(b []byte) []byte { return append(b, []byte(` {}`)...) },
		"nested":       func(b []byte) []byte { return bytes.Replace(b, []byte(`"format":1`), []byte(`"format":{}`), 1) },
		"invalid-utf8": func(b []byte) []byte { return bytes.Replace(b, []byte(Channel), []byte{0xff}, 1) },
	} {
		t.Run(name, func(t *testing.T) {
			b := change(bytes.Clone(raw))
			signed := []byte(base64.StdEncoding.EncodeToString(ed25519.Sign(key, append([]byte(SignatureDomain), b...))))
			if _, err := VerifyManifest(b, signed, pub, fixtureNow, nil); err == nil {
				t.Fatal("accepted noncanonical signed manifest")
			}
		})
	}
	for name, change := range map[string]func(*Manifest){
		"format": func(m *Manifest) { m.Format = 2 }, "channel": func(m *Manifest) { m.Channel = "remote" }, "compressed-budget": func(m *Manifest) { m.CompressedBytes = MaxCompressedBytes + 1 }, "raw-budget": func(m *Manifest) { m.Bytes = MaxDatabaseBytes + 1 }, "zero": func(m *Manifest) { m.Bytes = 0 }, "sha": func(m *Manifest) { m.SHA256 = strings.Repeat("A", 64) }, "source": func(m *Manifest) { m.Source = "http://127.0.0.1/key" }, "license": func(m *Manifest) { m.License = "proprietary" }, "attribution": func(m *Manifest) { m.AttributionURL = "https://evil.invalid" }, "future": func(m *Manifest) { m.Release = "2026-11" }, "epoch": func(m *Manifest) { m.BuildEpoch = math.MaxUint64 }, "old-build": func(m *Manifest) { m.BuildEpoch = 1 },
	} {
		t.Run(name, func(t *testing.T) {
			m := a.Manifest()
			change(&m)
			b, _ := json.Marshal(m)
			signature := []byte(base64.StdEncoding.EncodeToString(ed25519.Sign(key, append([]byte(SignatureDomain), b...))))
			if _, err := VerifyManifest(b, signature, pub, fixtureNow, nil); err == nil {
				t.Fatal("accepted invalid data authority")
			}
		})
	}
	bad := bytes.Clone(sig)
	bad[0] ^= 1
	if _, err := VerifyManifest(raw, bad, pub, fixtureNow, nil); err == nil {
		t.Fatal("signature mutation accepted")
	}
	if _, err := VerifyManifest(raw, []byte(base64.StdEncoding.EncodeToString(ed25519.Sign(key, raw))), pub, fixtureNow, nil); err == nil {
		t.Fatal("cross-domain signature accepted")
	}
	if _, err := VerifyManifest(raw, sig, make(ed25519.PublicKey, 32), fixtureNow, nil); err == nil {
		t.Fatal("wrong key accepted")
	}
	m := a.Manifest()
	m.SHA256 = strings.Repeat("0", 64)
	changed, _, _, _, _ := testAuthority(t, m)
	// Same sequence replacement uses a different key in this fixture too; the
	// previous-authority rule independently rejects changing its identity.
	if _, err := VerifyManifest(raw, sig, pub, fixtureNow, &changed); err == nil {
		t.Fatal("same-month replacement accepted")
	}
	previous := a
	previous.manifest.Release = "2026-11"
	if _, err := VerifyManifest(raw, sig, pub, fixtureNow, &previous); err == nil {
		t.Fatal("rollback accepted")
	}
	raw[0] = '['
	sig[0] = '!'
	if a.Manifest().Channel != Channel || a.SHA256() == "" {
		t.Fatal("authority aliases caller buffers")
	}
}

func TestSnapshotBytesChecksAndPrivateAddresses(t *testing.T) {
	s := openFixture(t, fixtureRecord())
	var decoded record
	if err := s.reader.Lookup(netip.MustParseAddr("8.8.8.8")).Decode(&decoded); err != nil {
		t.Fatal("synthetic typed MMDB decode:", err)
	}
	location := s.Lookup("8.8.8.8")
	if location.Status != "located" || location.CountryCode != "US" || location.City != "测试城市" || location.Region != "Test Region" || location.Latitude == nil || *location.Latitude != 12.3 {
		t.Fatalf("bad location: %+v", location)
	}
	if mapped := s.Lookup("::ffff:8.8.8.8"); mapped.CountryCode != location.CountryCode || mapped.Status != "located" {
		t.Fatal(mapped)
	}
	for _, ip := range []string{"127.0.0.1", "10.1.1.1", "100.64.1.1", "192.0.2.1", "198.18.1.1", "203.0.113.1", "240.1.1.1", "224.0.0.1", "::", "::1", "fc00::1", "fe80::1", "2001:db8::1", "2002:0808:0808::1", "64:ff9b::808:808", "3fff::1", "5f00::1"} {
		if got := s.Lookup(ip); got.Status != "non_public" || got.CountryCode != "" || got.Latitude != nil {
			t.Fatalf("private/reserved %s: %+v", ip, got)
		}
	}
	for _, ip := range []string{"", "garbage", "8.8.8.8:53", " 8.8.8.8", "fe80::1%eth0"} {
		if got := s.Lookup(ip); got.Status != "invalid_ip" {
			t.Fatal(ip, got)
		}
	}
	var missing *Snapshot
	if missing.Lookup("8.8.8.8").Status != "unavailable" || missing.Lookup("127.0.0.1").Status != "non_public" {
		t.Fatal("missing database lied")
	}
	metadata := s.Metadata(fixtureNow)
	if !metadata.Available || metadata.Attribution != Attribution || metadata.License != LicenseURL || metadata.Stale {
		t.Fatal(metadata)
	}
	if !s.Metadata(fixtureNow.AddDate(0, 4, 0)).Stale {
		t.Fatal("old data not marked stale")
	}
	if err := s.Close(); err != nil {
		t.Fatal(err)
	}
	if s.Lookup("8.8.8.8").Status != "unavailable" || s.Metadata(fixtureNow).Available {
		t.Fatal("closed snapshot claims availability")
	}
}

func TestSnapshotRejectsCorruptionCompressionAndCancellation(t *testing.T) {
	data := fixtureDatabase(fixtureRecord())
	compressed := gzipFixture(t, data)
	for name, change := range map[string]func() ([]byte, []byte, Manifest){
		"truncated-compressed": func() ([]byte, []byte, Manifest) {
			return data, compressed[:len(compressed)-1], manifestFor(data, compressed)
		},
		"extra-compressed": func() ([]byte, []byte, Manifest) {
			return data, append(bytes.Clone(compressed), 1), manifestFor(data, compressed)
		},
		"wrong-raw-sha": func() ([]byte, []byte, Manifest) {
			m := manifestFor(data, compressed)
			m.SHA256 = strings.Repeat("0", 64)
			return data, compressed, m
		},
		"signed-gzip-trailer": func() ([]byte, []byte, Manifest) {
			c := append(bytes.Clone(compressed), 1)
			return data, c, manifestFor(data, c)
		},
		"signed-multiple-members": func() ([]byte, []byte, Manifest) {
			c := append(bytes.Clone(compressed), compressed...)
			return data, c, manifestFor(data, c)
		},
		"signed-corrupt-checksum": func() ([]byte, []byte, Manifest) {
			c := bytes.Clone(compressed)
			c[len(c)-8] ^= 1
			return data, c, manifestFor(data, c)
		},
		"expanded-over-budget": func() ([]byte, []byte, Manifest) {
			m := manifestFor(data, compressed)
			m.Bytes--
			return data, compressed, m
		},
		"bad-mmdb": func() ([]byte, []byte, Manifest) {
			d := []byte("not mmdb")
			c := gzipFixture(t, d)
			return d, c, manifestFor(d, c)
		},
		"tree-cycle": func() ([]byte, []byte, Manifest) {
			d := bytes.Clone(data)
			d[2] = 0
			c := gzipFixture(t, d)
			return d, c, manifestFor(d, c)
		},
	} {
		t.Run(name, func(t *testing.T) {
			_, c, m := change()
			a, _, _, _, _ := testAuthority(t, m)
			if s, err := Open(context.Background(), a, bytes.NewReader(c)); err == nil {
				s.Close()
				t.Fatal("accepted corrupted archive")
			}
		})
	}
	a, _, _, _, _ := testAuthority(t, manifestFor(data, compressed))
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := Open(ctx, a, bytes.NewReader(compressed)); err == nil {
		t.Fatal("ignored cancellation")
	}
	if _, err := Open(context.Background(), Authority{}, bytes.NewReader(compressed)); err == nil {
		t.Fatal("accepted fabricated authority")
	}
}

func TestLocationMissingCoordinatesAndInvalidFields(t *testing.T) {
	row := fixtureRecord()
	delete(row, "location")
	got := openFixture(t, row).Lookup("8.8.8.8")
	if got.Status != "located" || got.Latitude != nil || got.Longitude != nil {
		t.Fatal("missing coordinates became zero", got)
	}
	for name, change := range map[string]func(map[string]any){
		"country":           func(r map[string]any) { r["country"].(map[string]any)["iso_code"] = "uS" },
		"country-unknown":   func(r map[string]any) { r["country"].(map[string]any)["iso_code"] = "ZZ" },
		"control-character": func(r map[string]any) { r["city"].(map[string]any)["names"].(map[string]any)["en"] = "city\nsecret" },
		"nan":               func(r map[string]any) { r["location"].(map[string]any)["latitude"] = math.NaN() },
		"longitude":         func(r map[string]any) { r["location"].(map[string]any)["longitude"] = float64(181) },
		"one-coordinate":    func(r map[string]any) { delete(r["location"].(map[string]any), "latitude") },
	} {
		t.Run(name, func(t *testing.T) {
			r := fixtureRecord()
			change(r)
			got := openFixture(t, r).Lookup("8.8.8.8")
			want := "lookup_error"
			if name == "country-unknown" {
				want = "not_found"
			}
			if got.Status != want || got.CountryCode != "" || got.Latitude != nil {
				t.Fatal(got)
			}
		})
	}
}

func TestConcurrentCloseAndLookup(t *testing.T) {
	s := openFixture(t, fixtureRecord())
	var wg sync.WaitGroup
	for i := 0; i < 12; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for range 1000 {
				location := s.Lookup("8.8.8.8")
				if location.Status != "located" && location.Status != "unavailable" {
					t.Error(location)
				}
				s.Metadata(fixtureNow)
			}
		}()
	}
	if err := s.Close(); err != nil {
		t.Fatal(err)
	}
	wg.Wait()
}

// Opt-in provider evidence. Unlike synthetic tests, this checks the exact
// official October 2026 bytes already downloaded over HTTPS. It uses a TEST
// key only to exercise the decoder; it does not prove release authorization.
func TestOfficialCityLiteOctober2026(t *testing.T) {
	file := os.Getenv("YUNZHAN_GEODATA_CITY_OCT2026")
	if file == "" {
		t.Skip("official data fixture not supplied; no provider evidence claimed")
	}
	compressed, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	if len(compressed) != 60193321 || hash(compressed) != "c839d407f85a1e0bddba354cef16b2c398182d1c34ed8d985555dce134b36b14" {
		t.Fatal("provider compressed bytes differ")
	}
	gz, err := gzip.NewReader(bytes.NewReader(compressed))
	if err != nil {
		t.Fatal(err)
	}
	raw, err := io.ReadAll(io.LimitReader(gz, MaxDatabaseBytes+1))
	if err != nil {
		t.Fatal(err)
	}
	gz.Close()
	if len(raw) != 126998165 || hash(raw) != "9e250f02722d1ad1780f88192f0e908af285478a33e76b88b349c9181ae9d0f5" {
		t.Fatal("provider raw bytes differ")
	}
	db, err := maxminddb.OpenBytes(raw)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("actual provider metadata: type=%s epoch=%d nodes=%d record_bits=%d", db.Metadata.DatabaseType, db.Metadata.BuildEpoch, db.Metadata.NodeCount, db.Metadata.RecordSize)
	m := manifestFor(raw, compressed)
	m.BuildEpoch = uint64(db.Metadata.BuildEpoch)
	db.Close()
	raw = nil
	a, _, _, _, _ := testAuthority(t, m)
	start := time.Now()
	s, err := Open(context.Background(), a, bytes.NewReader(compressed))
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close()
	t.Logf("actual full provider validation elapsed=%s", time.Since(start))
	for _, ip := range []string{"8.8.8.8", "1.1.1.1", "223.5.5.5", "2606:4700:4700::1111", "2001:4860:4860::8888"} {
		got := s.Lookup(ip)
		if got.Status != "located" || got.CountryCode == "" {
			t.Fatal(ip, got)
		}
		t.Logf("%s: %s country=%s region=%s city=%s approximate_coordinates=%t", ip, got.Status, got.CountryCode, got.Region, got.City, got.Latitude != nil)
	}
	metadata, _ := json.Marshal(s.Metadata(fixtureNow))
	t.Log("metadata=" + strconv.Quote(string(metadata)))
}
