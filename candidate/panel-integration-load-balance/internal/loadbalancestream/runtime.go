package loadbalancestream

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

const (
	MaxRuntimeBytes          = 1 << 20
	RuntimeWorkerConnections = 16384
	RuntimeOpenFiles         = 32768
	// An inactivity timeout does not bound an old TCP session's lifetime.
	// Bound graceful retiring workers too, below the manager's 630s stop limit.
	RuntimeDrainSeconds = 600
)

var ErrRuntime = errors.New("TCP/UDP 独立运行配置的完整入口、私有路径或资源规划无法核对")

type RuntimeEntry struct {
	Name          string
	Revision      int64
	Configuration Configuration
}

// RuntimeConfiguration is a complete private-instance configuration, not a
// request to modify a customer's global Nginx configuration or launch a service.
// Root must independently authorize the installed application, prove the private
// prefix/daemon identity, enforce cgroup/RLIMIT/host admission, journal the exact
// bytes and verify native syntax, owned listeners and the original generation.
type RuntimeConfiguration struct {
	Main                      []byte
	SHA256                    string
	Entries                   []RuntimeEntry
	ActiveEntries             int
	PlannedBufferAndZoneBytes int64
	RequiredOpenFiles         int
	WorkerConnections         int
}

// A syntactically safe path is NOT an ownership proof. Only the trusted Root
// controller may select a prefix; this function never checks/creates directories
// or accepts a browser-supplied path as filesystem authority.
func privateRuntimePrefix(prefix string) bool {
	if len(prefix) < 2 || len(prefix) > 512 || !filepath.IsAbs(prefix) || filepath.Clean(prefix) != prefix || strings.HasSuffix(prefix, "/") {
		return false
	}
	for _, part := range strings.Split(prefix[1:], "/") {
		if part == "" || part == "." || part == ".." || len(part) > 255 {
			return false
		}
		for _, c := range []byte(part) {
			if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-' || c == '_' || c == '.') {
				return false
			}
		}
	}
	return true
}

// RenderRuntime renders the COMPLETE validated set in a deterministic order.
// It never infers a listener/health/installation result from the generated bytes.
// Buffer/zone planning is not a measured RSS value or an enforced memory limit.
func RenderRuntime(current []Entry, prefix string, facts ValidationContext) (RuntimeConfiguration, error) {
	if !privateRuntimePrefix(prefix) || ValidateSet(current, facts) != nil {
		return RuntimeConfiguration{}, ErrRuntime
	}
	entries := make([]Entry, len(current))
	for i, entry := range current {
		entries[i] = copyEntry(entry)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name < entries[j].Name })
	result := RuntimeConfiguration{Entries: make([]RuntimeEntry, 0, len(entries)), RequiredOpenFiles: RuntimeOpenFiles, WorkerConnections: RuntimeWorkerConnections}
	var http, stream bytes.Buffer
	for _, entry := range entries {
		configuration, err := Render(entry)
		if err != nil {
			return RuntimeConfiguration{}, ErrRuntime
		}
		result.Entries = append(result.Entries, RuntimeEntry{Name: entry.Name, Revision: entry.Revision, Configuration: configuration})
		if !entry.Removed {
			result.ActiveEntries++
			result.PlannedBufferAndZoneBytes += FixedBytesPerEntry + int64(entry.MaxSessions)*BytesPerSession
		}
		http.Write(configuration.HTTP)
		stream.Write(configuration.Stream)
		if http.Len()+stream.Len() > MaxRuntimeBytes-4096 {
			return RuntimeConfiguration{}, ErrRuntime
		}
	}
	// The fixed worker/descriptor ceilings exceed the maximum sessions admitted
	// by the unchanged <=1GiB buffer/zone planner, including paired TCP sockets,
	// all probe/listening sockets and a fixed reserve. They do not raise a host's
	// rlimit; the controller must prove the real service limit before activation.
	var main bytes.Buffer
	fmt.Fprintf(&main, "# managed by panel; private TCP/UDP load-balance instance\nworker_processes 1;\nworker_shutdown_timeout %ds;\npid %s/nginx.pid;\nerror_log stderr warn;\nevents { worker_connections %d; }\nhttp {\n  access_log off;\n  server_tokens off;\n  client_max_body_size 1k;\n  client_header_timeout 1s;\n  client_body_timeout 1s;\n  send_timeout 1s;\n  keepalive_timeout 0;\n  large_client_header_buffers 2 1k;\n", RuntimeDrainSeconds, prefix, RuntimeWorkerConnections)
	main.Write(http.Bytes())
	main.WriteString("}\nstream {\n")
	main.Write(stream.Bytes())
	main.WriteString("}\n")
	if main.Len() > MaxRuntimeBytes || result.PlannedBufferAndZoneBytes > facts.MemoryBudgetBytes {
		return RuntimeConfiguration{}, ErrRuntime
	}
	result.Main = append([]byte(nil), main.Bytes()...)
	digest := sha256.Sum256(result.Main)
	result.SHA256 = hex.EncodeToString(digest[:])
	return result, nil
}
