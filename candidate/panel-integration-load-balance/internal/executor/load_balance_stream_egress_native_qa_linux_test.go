package executor

import (
	"bytes"
	"context"
	"os"
	"os/exec"
	"reflect"
	"strings"
	"syscall"
	"testing"
	"time"

	"local/panel/internal/loadbalancestream"
)

// This component test must run in a NEW network namespace, independently
// checked against PID 1, with the host's exact namespace and trusted nft hash
// supplied by the closed native runner. It never configures a service, writes
// NSS, signals installed processes or grants original-controller authority.
func TestLoadBalanceStreamEgressNativePrivateNamespaceHeldOriginalOnly(t *testing.T) {
	if os.Getenv("PANEL_NATIVE_QA") != "1" || os.Getenv("PANEL_LBSTREAM_EGRESS_PRIVATE_NETNS_QA") != "20261027" {
		t.Skip("explicit isolated-network-namespace egress component only")
	}
	host, e1 := os.Readlink("/proc/1/ns/net")
	self, e2 := os.Readlink("/proc/self/ns/net")
	expectedHost := os.Getenv("PANEL_LBSTREAM_EGRESS_QA_HOST_NETNS")
	expectedSHA := os.Getenv("PANEL_LBSTREAM_EGRESS_QA_NFT_SHA256")
	if os.Geteuid() != 0 || os.Getegid() != 0 || e1 != nil || e2 != nil || host == self || host != expectedHost ||
		!strings.HasPrefix(host, "net:[") || !loadBalanceStreamAccountHash(expectedSHA) {
		t.Fatal("new non-host network namespace, Root and independently pinned nft are required BEFORE effects")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 40*time.Second)
	defer cancel()
	g := &loadBalanceStreamHeldEgress{missing: true}
	defer g.close()
	var err error
	g.nft, _, err = holdLoadBalanceStreamEngineFile(streamEgressNFT, true)
	if err != nil || g.nft.sha != expectedSHA {
		t.Fatal("fixed trusted actual nft ELF mismatch", err)
	}
	g.namespace, err = os.Open("/proc/self/ns/net")
	if err != nil {
		t.Fatal(err)
	}
	g.nsBefore, err = g.namespace.Stat()
	if err != nil {
		t.Fatal(err)
	}
	st, ok := g.nsBefore.Sys().(*syscall.Stat_t)
	boot, err := streamAccountParentProc("/proc/sys/kernel/random/boot_id", 128)
	if !ok || err != nil || st.Dev == 0 || st.Ino == 0 {
		t.Fatal("actual namespace identity unavailable", err)
	}
	g.bootID = strings.TrimSuffix(string(boot), "\n")
	g.receipt = streamEgressReceipt{Format: 1, BootID: g.bootID, NetnsDevice: uint64(st.Dev), NetnsInode: st.Ino, NftSHA256: g.nft.sha}
	if !g.identityCurrent(ctx) || g.current(ctx) != nil {
		t.Fatal("actual private kernel namespace did not prove initial absence")
	}
	// All fixture commands below are test-only and confined by the explicit
	// namespace check above; the production method has fixed read argv and only
	// receives batches generated by the reviewed pure policy builder.
	fixture := func(args []string, input string, wantOK bool) []byte {
		t.Helper()
		commandCtx, done := context.WithTimeout(ctx, 3*time.Second)
		defer done()
		cmd := exec.CommandContext(commandCtx, "/proc/self/fd/3", args...)
		cmd.Args[0], cmd.ExtraFiles = streamEgressNFT, []*os.File{g.nft.file}
		cmd.Env = []string{"PATH=/usr/sbin:/usr/bin:/sbin:/bin", "LANG=C", "LC_ALL=C"}
		cmd.Stdin = strings.NewReader(input)
		out, diagnostic := &boundedBuffer{max: loadbalancestream.MaxEgressObservationBytes}, &boundedBuffer{max: 16384}
		cmd.Stdout, cmd.Stderr, cmd.WaitDelay = out, diagnostic, time.Second
		err := cmd.Run()
		if out.truncated || diagnostic.truncated || (err == nil) != wantOK || wantOK && diagnostic.String() != "" {
			t.Fatalf("private fixture command outcome: %v %.500s", err, diagnostic.String())
		}
		return []byte(out.String())
	}
	fixture([]string{"-f", "-"}, "add table inet qa_l4_egress_foreign { flags dormant; comment \"unrelated private QA\"; }\n", true)
	foreign := fixture([]string{"-s", "-a", "-j", "list", "table", "inet", "qa_l4_egress_foreign"}, "", true)
	if err := g.current(ctx); err != nil {
		inventory, readErr := g.command(ctx, nil, true)
		t.Fatalf("foreign dormant table must not prevent complete own-table absence proof: current=%v identity=%t read=%v inventory=%.4096s", err, g.identityCurrent(ctx), readErr, inventory)
	}
	_, rawSeed, _ := streamServiceReceiptFixture(t, "running")
	seed, err := loadbalancestream.DecodeControlSeed(rawSeed)
	if err != nil {
		t.Fatal(err)
	}
	policy, err := streamReceiptEgressPolicy(seed, "running", 991)
	if err != nil {
		t.Fatal(err)
	}
	if err := g.replaceOriginal(ctx, policy); err != nil || g.missing || !g.receipt.valid(policy) || g.current(ctx) != nil {
		t.Fatal("actual held nft must create and re-observe one complete private table", err)
	}
	first := g.receipt.Observation
	first.RuleHandles = append([]uint64(nil), first.RuleHandles...)
	readOwn := func() []byte {
		t.Helper()
		raw, err := g.command(ctx, nil, false)
		if err != nil {
			t.Fatal("complete current table read failed", err)
		}
		return raw
	}
	initial := readOwn()
	originalReceipt := g.receipt
	originalReceipt.Observation.RuleHandles = append([]uint64(nil), g.receipt.Observation.RuleHandles...)
	reader, err := holdLoadBalanceStreamRecordedEgress(ctx, seed, "running", 991, originalReceipt)
	if err != nil || reader == nil || !reader.readOnly || reader.issued || reader.missing || reader.current(ctx) != nil {
		t.Fatal("actual original receipt must admit only held read-only observation", err)
	}
	defer reader.close()
	t.Run("recorded-observer-does-not-retain-caller-rule-handle-buffer", func(t *testing.T) {
		original := originalReceipt.Observation.RuleHandles[0]
		originalReceipt.Observation.RuleHandles[0]++
		defer func() { originalReceipt.Observation.RuleHandles[0] = original }()
		if reader.current(ctx) != nil {
			t.Fatal("caller mutation replaced a held observer's original rule handles")
		}
	})
	t.Run("recorded-observer-cannot-issue-even-a-valid-nft-write", func(t *testing.T) {
		if raw, err := reader.command(ctx, []byte("flush ruleset\n"), false); err != loadbalancestream.ErrEgressGuard || raw != nil ||
			!bytes.Equal(initial, readOwn()) || reader.current(ctx) != nil {
			t.Fatal("read-only observer selected a write or lost its actual original table")
		}
	})
	t.Run("saved-fields-and-phase-claims-do-not-grant-live-ownership", func(t *testing.T) {
		for name, mutate := range map[string]func(){
			"receipt-format":  func() { g.receipt.Format = 2 },
			"receipt-boot":    func() { g.receipt.BootID = "a7000000-0000-4000-8000-000000000001" },
			"receipt-device":  func() { g.receipt.NetnsDevice++ },
			"receipt-inode":   func() { g.receipt.NetnsInode++ },
			"receipt-tool":    func() { g.receipt.NftSHA256 = strings.Repeat("f", 64) },
			"saved-table":     func() { g.receipt.Observation.TableHandle++ },
			"saved-chain":     func() { g.receipt.Observation.ChainHandle++ },
			"saved-rule":      func() { g.receipt.Observation.RuleHandles[0]++ },
			"saved-order":     func() { h := g.receipt.Observation.RuleHandles; h[0], h[1] = h[1], h[0] },
			"unknown-outcome": func() { g.unknown = true },
			"different-boot":  func() { g.bootID = "a7000000-0000-4000-8000-000000000001" },
			"different-tool":  func() { g.nft.path = "/usr/sbin/another-nft" },
			"missing-netns":   func() { g.namespace = nil },
		} {
			t.Run(name, func(t *testing.T) {
				original := *g
				original.receipt.Observation.RuleHandles = append([]uint64(nil), g.receipt.Observation.RuleHandles...)
				originalPath := g.nft.path
				restore := func() {
					*g = original
					g.nft.path = originalPath
				}
				defer restore()
				mutate()
				if g.current(ctx) != loadbalancestream.ErrEgressGuard || g.replaceOriginal(ctx, policy) != loadbalancestream.ErrEgressGuard {
					t.Fatal("saved or substituted original adopted the live kernel table")
				}
				restore()
				if !bytes.Equal(initial, readOwn()) || g.current(ctx) != nil {
					t.Fatal("refusal changed the table or discarded the original held descriptors")
				}
			})
		}
		for _, p := range []*loadBalanceStreamConfigurationPublication{nil, {}, {promoted: true, store: &loadBalanceStreamConfigurationStore{egress: g}}} {
			if p.applyEgressOwned(ctx, nil) != loadbalancestream.ErrEgressGuard || p.retireStoppedEgressOwned(ctx, nil, nil) != loadbalancestream.ErrEgressGuard {
				t.Fatal("component rule observation improperly substituted for original controller authority")
			}
		}
	})
	t.Run("failed-command-does-not-mean-absence", func(t *testing.T) {
		for _, batch := range [][]byte{{}, []byte("this_is_not_a_valid_nft_transaction\n")} {
			if _, err := g.command(ctx, batch, false); err != loadbalancestream.ErrEgressGuard {
				t.Fatal("invalid or failed fixed-tool command was accepted")
			}
		}
		if _, err := g.command(ctx, []byte("flush ruleset\n"), true); err != loadbalancestream.ErrEgressGuard {
			t.Fatal("invalid read-plus-batch form was accepted")
		}
		if !bytes.Equal(initial, readOwn()) || g.current(ctx) != nil {
			t.Fatal("failed command changed a table or fabricated absence")
		}
	})
	t.Run("replacement-retains-table-and-chain-and-retires-old-destinations", func(t *testing.T) {
		validation := loadbalancestream.ValidationContext{PanelControlPorts: []int{19100, 19102, 19080}, MemoryBudgetBytes: loadbalancestream.MaxMemoryBudget}
		entries := append([]loadbalancestream.Entry(nil), seed.After...)
		entries[0].Nodes = []loadbalancestream.Node{{Address: "192.0.2.12:41003", Weight: 1}, {Address: "192.0.2.13:41004", Weight: 3}}
		next, err := loadbalancestream.PlanEgressGuard(entries, seed.After, validation, 991)
		if err != nil || g.replaceOriginal(ctx, next) != nil || g.current(ctx) != nil {
			t.Fatal("dual-generation rule replacement failed", err)
		}
		second := g.receipt.Observation
		if first.TableHandle != second.TableHandle || first.ChainHandle != second.ChainHandle || reflect.DeepEqual(first.RuleHandles, second.RuleHandles) || first.PolicySHA256 == second.PolicySHA256 {
			t.Fatal("replacement recreated a table/chain or reused previous rule/receipt data")
		}
		if reader.current(ctx) != loadbalancestream.ErrEgressGuard {
			t.Fatal("a held status/upgrade observation adopted replaced rules")
		}
		stale, staleErr := holdLoadBalanceStreamRecordedEgress(ctx, seed, "running", 991, originalReceipt)
		if stale != nil || staleErr != loadbalancestream.ErrEgressGuard {
			t.Fatal("reopening a historical receipt adopted another policy")
		}
		empty, err := loadbalancestream.PlanEgressGuard(nil, nil, validation, 991)
		if err != nil || g.replaceOriginal(ctx, empty) != nil || g.current(ctx) != nil || !g.receipt.valid(empty) {
			t.Fatal("last-stop exact empty permission set failed", err)
		}
		if g.receipt.Observation.TableHandle != first.TableHandle || g.receipt.Observation.ChainHandle != first.ChainHandle {
			t.Fatal("retirement must retain original table and chain identities")
		}
	})
	t.Run("foreign-or-modified-owned-table-is-never-adopted-or-replaced", func(t *testing.T) {
		other := *g
		other.missing = true
		if other.current(ctx) != loadbalancestream.ErrEgressGuard || other.replaceOriginal(ctx, policy) != loadbalancestream.ErrEgressGuard {
			t.Fatal("existing table was adopted as a fresh installation")
		}
		fixture([]string{"-f", "-"}, "add rule inet panel_lbstream output counter comment \"external-private-QA-change\"\n", true)
		changed := readOwn()
		if g.current(ctx) != loadbalancestream.ErrEgressGuard || g.replaceOriginal(ctx, policy) != loadbalancestream.ErrEgressGuard || !bytes.Equal(changed, readOwn()) {
			t.Fatal("modified owned table was repaired/adopted or changed on refusal")
		}
	})
	fixture([]string{"delete", "table", "inet", loadbalancestream.EgressTableName}, "", true)
	if reader.current(ctx) != loadbalancestream.ErrEgressGuard {
		t.Fatal("a removed firewall table was treated as a verified status")
	}
	absent, absentErr := holdLoadBalanceStreamRecordedEgress(ctx, seed, "running", 991, originalReceipt)
	if absent != nil || absentErr != loadbalancestream.ErrEgressGuard {
		t.Fatal("a retained receipt hid actual table absence")
	}
	if got := fixture([]string{"-s", "-a", "-j", "list", "table", "inet", "qa_l4_egress_foreign"}, "", true); !bytes.Equal(got, foreign) {
		t.Fatal("unrelated private foreign table changed")
	}
	t.Logf("component_only=true original_controller_activated=false host_netns=%s private_netns=%s nft_sha256=%s original_table=%d original_chain=%d", host, self, expectedSHA, first.TableHandle, first.ChainHandle)
}
